demoForm.addEventListener("submit", async event => {
  event.preventDefault();

  const formData = new FormData(demoForm);
  const payload = {
    name: String(formData.get("name") || "").trim(),
    phone: String(formData.get("phone") || "").trim(),
    company: String(formData.get("company") || "").trim(),
    industry: String(formData.get("industry") || "").trim(),
    message: String(formData.get("message") || "").trim(),
  };

  if (payload.industry === "其它行业") {
    payload.industry = String(formData.get("industryOther") || "").trim();
  }

  const error = validateDemoForm(payload);

  if (error) {
    setDemoStatus(error, "error");
    return;
  }

  const submitButton = demoForm.querySelector(".demo-submit");
  submitButton.disabled = true;
  setDemoStatus(getCopy("demoSubmitting"));

  try {
    const response = await fetch("/api/demo-requests", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
    });
    const result = await response.json();

    if (!response.ok || !result.ok) {
      setDemoStatus(result.error || getCopy("demoSubmitError"), "error");
      return;
    }

    resetDemoForm();
    showDemoSuccess();
  } catch (error) {
    setDemoStatus(getCopy("demoNetworkError"), "error");
  } finally {
    submitButton.disabled = false;
  }
});

